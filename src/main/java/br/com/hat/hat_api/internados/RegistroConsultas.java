package br.com.hat.hat_api.internados;

import br.com.hat.hat_api.painel.BancoPainel;
import org.springframework.stereotype.Component;

import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Registro de quem consultou os pacientes internados, o quê e quando (LGPD), no banco do painel
 * (tabela INTERNADOS_CONSULTA, criada na primeira gravação). Sem o banco do painel a tela não abre:
 * dado pessoal sensível só sai com o registro.
 */
@Component
public class RegistroConsultas {

    static final Set<String> ACOES = Set.of("LISTA", "BUSCA", "FICHA");
    static final int MAX_BUSCA = 200;
    private final BancoPainel banco;
    private volatile boolean pronto;

    public RegistroConsultas(BancoPainel banco) {
        this.banco = banco;
    }

    synchronized void preparar() {
        if (pronto) return;
        var jdbc = banco.jdbc();
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS INTERNADOS_CONSULTA (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    QUANDO TIMESTAMP NOT NULL,
                    USUARIO VARCHAR(100) NOT NULL,
                    ACAO VARCHAR(10) NOT NULL,
                    BUSCA VARCHAR(200),
                    CAMPO VARCHAR(20),
                    BLOCO VARCHAR(20),
                    REG BIGINT,
                    RESULTADOS INTEGER
                )""");
        jdbc.execute("CREATE INDEX IF NOT EXISTS IX_INTERNADOS_CONSULTA_QUANDO ON INTERNADOS_CONSULTA (QUANDO)");
        pronto = true;
    }

    /** Grava uma consulta. Ação fora da lista = {@link DadoInvalido}; banco fora = {@link BancoPainel.BancoDesligado}. */
    public void registrar(String usuario, Internados.Registro r) {
        String acao = r == null || r.acao() == null ? "" : r.acao().trim().toUpperCase(Locale.ROOT);
        if (!ACOES.contains(acao)) throw new DadoInvalido("Ação do registro inválida: use LISTA, BUSCA ou FICHA.");
        preparar();
        banco.jdbc().update("INSERT INTO INTERNADOS_CONSULTA (QUANDO, USUARIO, ACAO, BUSCA, CAMPO, BLOCO, REG, RESULTADOS) VALUES (?,?,?,?,?,?,?,?)",
                Timestamp.valueOf(LocalDateTime.now()), usuario, acao, corta(r.busca(), MAX_BUSCA), corta(r.campo(), 20),
                corta(r.bloco(), 20), r.reg(), r.resultados());
    }

    /** As últimas consultas (mais nova primeiro), para conferência. */
    public List<Internados.Linha> ultimas(int limite) {
        preparar();
        return banco.jdbc().query("SELECT QUANDO, USUARIO, ACAO, BUSCA, CAMPO, BLOCO, REG, RESULTADOS FROM INTERNADOS_CONSULTA ORDER BY QUANDO DESC, ID DESC LIMIT ?",
                (rs, i) -> new Internados.Linha(rs.getTimestamp(1).toLocalDateTime(), rs.getString(2), rs.getString(3), rs.getString(4),
                        rs.getString(5), rs.getString(6), (Long) rs.getObject(7, Long.class), (Integer) rs.getObject(8, Integer.class)),
                Math.max(1, Math.min(limite, 5000)));
    }

    private static String corta(String s, int max) {
        if (s == null) return null;
        String t = s.trim();
        if (t.isEmpty()) return null;
        return t.length() > max ? t.substring(0, max) : t;
    }

    /** Pedido de registro com dado fora do esperado. */
    public static class DadoInvalido extends RuntimeException {
        public DadoInvalido(String m) {
            super(m);
        }
    }
}
