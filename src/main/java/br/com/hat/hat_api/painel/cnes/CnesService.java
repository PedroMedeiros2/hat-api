package br.com.hat.hat_api.painel.cnes;

import br.com.hat.hat_api.painel.BancoPainel;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.io.InputStream;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Cadastro CNES do painel: guardado no banco do painel (tabelas CNES_LEITO e CNES_HISTORICO, criadas ao
 * subir). Na primeira vez, o banco é preenchido com o cadastro que estava no código do painel
 * (resources/cnes/leitos-inicial.json). Sem banco configurado, a leitura usa esse mesmo arquivo.
 * Toda criação e mudança grava quem, quando, o quê, de e para.
 */
@Service
public class CnesService {

    private static final Logger LOG = LoggerFactory.getLogger(CnesService.class);
    static final Set<String> PERFIS = Set.of("SUS", "CONV/PART");
    /** Tipo dos blocos sem tipo definido. */
    public static final String TIPO_PADRAO = "FIXO";
    /** Tipos com que o cadastro começa (a gestão muda os nomes e as regras e cria outros). */
    static final List<LeitoCnes.TipoLeito> TIPOS_INICIAIS = List.of(
            new LeitoCnes.TipoLeito("FIXO", "Fixo", true, false, "Leito de internação: entra no total de leitos e na taxa de ocupação.", 1),
            new LeitoCnes.TipoLeito("PROVISORIO", "Provisório", false, true, "Maca ou leito de passagem (PS e PA): fora da taxa, mostrado à parte.", 2),
            new LeitoCnes.TipoLeito("VIRTUAL", "Virtual", false, false, "Leito que existe só no sistema (ex.: leito extra ou administrativo): não conta na ocupação.", 3));
    /** Blocos com tipo definido no começo: PS e PA eram provisórios no código do painel. */
    static final List<LeitoCnes.BlocoTipo> BLOCOS_INICIAIS = List.of(new LeitoCnes.BlocoTipo("PS", "PROVISORIO"), new LeitoCnes.BlocoTipo("PA", "PROVISORIO"));
    private final BancoPainel banco;
    private final ObjectMapper json = new ObjectMapper();
    private volatile boolean pronto;

    public CnesService(BancoPainel banco) {
        this.banco = banco;
    }

    /** Ao subir, já cria as tabelas e o cadastro inicial; com o banco fora, tenta de novo na primeira chamada. */
    @EventListener(ApplicationReadyEvent.class)
    public void aoSubir() {
        if (!banco.configurado()) {
            LOG.info("Banco do painel não configurado (INDICADORES_DB_URL): cadastro CNES só para leitura.");
            return;
        }
        try {
            preparar();
            LOG.info("Cadastro CNES pronto no banco do painel.");
        } catch (RuntimeException e) {
            LOG.warn("Banco do painel indisponível ao subir; o cadastro CNES tenta de novo na primeira chamada: {}", e.getMessage());
        }
    }

    /** Cria as tabelas e o cadastro inicial (uma vez por execução; idempotente). */
    synchronized void preparar() {
        if (pronto || !banco.configurado()) return;
        var jdbc = banco.jdbc();
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS CNES_LEITO (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    BLOCO VARCHAR(20) NOT NULL,
                    QUARTO VARCHAR(20) NOT NULL,
                    LEITO VARCHAR(20) NOT NULL,
                    PERFIL VARCHAR(10) NOT NULL,
                    ESPECIALIDADE VARCHAR(80) NOT NULL,
                    OBSERVACAO VARCHAR(255),
                    ORDEM INT NOT NULL DEFAULT 0,
                    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
                    ATUALIZADO_EM TIMESTAMP NOT NULL,
                    ATUALIZADO_POR VARCHAR(100) NOT NULL
                )""");
        jdbc.execute("CREATE INDEX IF NOT EXISTS IX_CNES_LEITO_BLOCO ON CNES_LEITO (BLOCO, ORDEM)");
        jdbc.execute("ALTER TABLE CNES_LEITO ADD COLUMN IF NOT EXISTS TIPO VARCHAR(20)");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS CNES_TIPO (
                    CODIGO VARCHAR(20) PRIMARY KEY,
                    NOME VARCHAR(40) NOT NULL,
                    CONTA_TAXA BOOLEAN NOT NULL,
                    A_PARTE BOOLEAN NOT NULL,
                    DESCRICAO VARCHAR(255),
                    ORDEM INT NOT NULL DEFAULT 0,
                    ATUALIZADO_EM TIMESTAMP NOT NULL,
                    ATUALIZADO_POR VARCHAR(100) NOT NULL
                )""");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS CNES_BLOCO (
                    BLOCO VARCHAR(20) PRIMARY KEY,
                    TIPO VARCHAR(20) NOT NULL,
                    ATUALIZADO_EM TIMESTAMP NOT NULL,
                    ATUALIZADO_POR VARCHAR(100) NOT NULL
                )""");
        Integer nTipos = jdbc.queryForObject("SELECT COUNT(*) FROM CNES_TIPO", Integer.class);
        if (nTipos != null && nTipos == 0) {
            Timestamp agora = Timestamp.valueOf(LocalDateTime.now());
            for (LeitoCnes.TipoLeito t : TIPOS_INICIAIS) {
                jdbc.update("INSERT INTO CNES_TIPO (CODIGO, NOME, CONTA_TAXA, A_PARTE, DESCRICAO, ORDEM, ATUALIZADO_EM, ATUALIZADO_POR) VALUES (?,?,?,?,?,?,?,?)",
                        t.codigo(), t.nome(), t.contaNaTaxa(), t.aParte(), t.descricao(), t.ordem(), agora, "importação inicial");
            }
            Integer nBlocos = jdbc.queryForObject("SELECT COUNT(*) FROM CNES_BLOCO", Integer.class);
            if (nBlocos != null && nBlocos == 0) {
                for (LeitoCnes.BlocoTipo b : BLOCOS_INICIAIS) {
                    jdbc.update("INSERT INTO CNES_BLOCO (BLOCO, TIPO, ATUALIZADO_EM, ATUALIZADO_POR) VALUES (?,?,?,?)", b.bloco(), b.tipo(), agora, "importação inicial");
                }
            }
        }
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS CNES_HISTORICO (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    QUANDO TIMESTAMP NOT NULL,
                    USUARIO VARCHAR(100) NOT NULL,
                    ACAO VARCHAR(20) NOT NULL,
                    LEITO_ID BIGINT,
                    BLOCO VARCHAR(20),
                    ANTES VARCHAR(1000),
                    DEPOIS VARCHAR(1000)
                )""");
        jdbc.execute("CREATE INDEX IF NOT EXISTS IX_CNES_HISTORICO_QUANDO ON CNES_HISTORICO (QUANDO)");
        Integer total = jdbc.queryForObject("SELECT COUNT(*) FROM CNES_LEITO", Integer.class);
        if (total != null && total == 0) {
            LocalDateTime agora = LocalDateTime.now();
            for (LeitoCnes l : inicial()) {
                jdbc.update("INSERT INTO CNES_LEITO (BLOCO, QUARTO, LEITO, PERFIL, ESPECIALIDADE, OBSERVACAO, ORDEM, ATIVO, ATUALIZADO_EM, ATUALIZADO_POR) VALUES (?,?,?,?,?,?,?,TRUE,?,?)",
                        l.bloco(), l.quarto(), l.leito(), l.perfil(), l.especialidade(), l.observacao(), l.ordem(), Timestamp.valueOf(agora), "importação inicial");
            }
            jdbc.update("INSERT INTO CNES_HISTORICO (QUANDO, USUARIO, ACAO, ANTES, DEPOIS) VALUES (?,?,?,?,?)",
                    Timestamp.valueOf(agora), "importação inicial", "IMPORTAR", null, inicial().size() + " leitos do cadastro que estava no código do painel");
        }
        pronto = true;
    }

    /** Leitos, tipos e o tipo de cada bloco. */
    public LeitoCnes.Cadastro cadastro() {
        return new LeitoCnes.Cadastro(editavel(), listar(), tipos(), blocos(), TIPO_PADRAO);
    }

    public List<LeitoCnes.TipoLeito> tipos() {
        if (!banco.configurado()) return TIPOS_INICIAIS;
        preparar();
        return banco.jdbc().query("SELECT * FROM CNES_TIPO ORDER BY ORDEM, NOME", (r, i) -> new LeitoCnes.TipoLeito(
                r.getString("codigo"), r.getString("nome"), r.getBoolean("conta_taxa"), r.getBoolean("a_parte"), r.getString("descricao"), r.getInt("ordem")));
    }

    public List<LeitoCnes.BlocoTipo> blocos() {
        if (!banco.configurado()) return BLOCOS_INICIAIS;
        preparar();
        return banco.jdbc().query("SELECT BLOCO, TIPO FROM CNES_BLOCO ORDER BY BLOCO", (r, i) -> new LeitoCnes.BlocoTipo(r.getString(1), r.getString(2)));
    }

    /** Cria ou muda um tipo de leito (o código não muda depois de criado). */
    public LeitoCnes.TipoLeito salvarTipo(String codigoBruto, LeitoCnes.DadosTipo d, String usuario) {
        preparar();
        String codigo = codigoBruto == null ? "" : codigoBruto.trim().toUpperCase();
        if (!codigo.matches("[A-Z0-9_]{2,20}")) throw new DadoInvalido("Código do tipo: de 2 a 20 letras, números ou _ (ex.: VIRTUAL).");
        if (d == null || vazio(d.nome()) || d.nome().trim().length() > 40) throw new DadoInvalido("Dê um nome ao tipo (até 40 letras).");
        boolean taxa = Boolean.TRUE.equals(d.contaNaTaxa()), parte = Boolean.TRUE.equals(d.aParte());
        if (taxa && parte) throw new DadoInvalido("Um tipo não pode contar na taxa e ficar à parte ao mesmo tempo.");
        LocalDateTime agora = LocalDateTime.now();
        var antes = tipos().stream().filter(t -> t.codigo().equals(codigo)).findFirst();
        int ordem = d.ordem() != null ? d.ordem() : antes.map(LeitoCnes.TipoLeito::ordem).orElse(tipos().size() + 1);
        if (antes.isPresent()) {
            banco.jdbc().update("UPDATE CNES_TIPO SET NOME=?, CONTA_TAXA=?, A_PARTE=?, DESCRICAO=?, ORDEM=?, ATUALIZADO_EM=?, ATUALIZADO_POR=? WHERE CODIGO=?",
                    d.nome().trim(), taxa, parte, vazioNulo(d.descricao()), ordem, Timestamp.valueOf(agora), usuario, codigo);
        } else {
            banco.jdbc().update("INSERT INTO CNES_TIPO (CODIGO, NOME, CONTA_TAXA, A_PARTE, DESCRICAO, ORDEM, ATUALIZADO_EM, ATUALIZADO_POR) VALUES (?,?,?,?,?,?,?,?)",
                    codigo, d.nome().trim(), taxa, parte, vazioNulo(d.descricao()), ordem, Timestamp.valueOf(agora), usuario);
        }
        LeitoCnes.TipoLeito depois = new LeitoCnes.TipoLeito(codigo, d.nome().trim(), taxa, parte, vazioNulo(d.descricao()), ordem);
        banco.jdbc().update("INSERT INTO CNES_HISTORICO (QUANDO, USUARIO, ACAO, ANTES, DEPOIS) VALUES (?,?,?,?,?)",
                Timestamp.valueOf(agora), usuario, antes.isPresent() ? "TIPO" : "TIPO_NOVO", antes.map(CnesService::textoTipo).orElse(null), textoTipo(depois));
        return depois;
    }

    /** Define o tipo padrão de um bloco (tipo nulo ou vazio = volta ao padrão, Fixo). */
    public LeitoCnes.BlocoTipo definirTipoBloco(String blocoBruto, String tipoBruto, String usuario) {
        preparar();
        String bloco = blocoBruto == null ? "" : blocoBruto.trim().toUpperCase();
        if (bloco.isEmpty() || bloco.length() > 20) throw new DadoInvalido("Bloco inválido.");
        String tipo = vazio(tipoBruto) ? TIPO_PADRAO : tipoBruto.trim().toUpperCase();
        validarTipo(tipo);
        String antes = blocos().stream().filter(b -> b.bloco().equals(bloco)).map(LeitoCnes.BlocoTipo::tipo).findFirst().orElse(TIPO_PADRAO);
        LocalDateTime agora = LocalDateTime.now();
        banco.jdbc().update("DELETE FROM CNES_BLOCO WHERE BLOCO = ?", bloco);
        if (!TIPO_PADRAO.equals(tipo)) {
            banco.jdbc().update("INSERT INTO CNES_BLOCO (BLOCO, TIPO, ATUALIZADO_EM, ATUALIZADO_POR) VALUES (?,?,?,?)", bloco, tipo, Timestamp.valueOf(agora), usuario);
        }
        banco.jdbc().update("INSERT INTO CNES_HISTORICO (QUANDO, USUARIO, ACAO, BLOCO, ANTES, DEPOIS) VALUES (?,?,?,?,?,?)",
                Timestamp.valueOf(agora), usuario, "BLOCO", bloco, "tipo do bloco: " + antes, "tipo do bloco: " + tipo);
        return new LeitoCnes.BlocoTipo(bloco, tipo);
    }

    private void validarTipo(String tipo) {
        if (tipos().stream().noneMatch(t -> t.codigo().equals(tipo))) throw new DadoInvalido("Tipo de leito " + tipo + " não existe.");
    }

    private static String textoTipo(LeitoCnes.TipoLeito t) {
        return String.format("%s (%s) · %s", t.nome(), t.codigo(), t.contaNaTaxa() ? "conta na taxa" : t.aParte() ? "fora da taxa, à parte" : "não conta");
    }

    /** O cadastro todo (ativos e inativos), na ordem do bloco. */
    public List<LeitoCnes> listar() {
        if (!banco.configurado()) return inicial();
        preparar();
        return banco.jdbc().query("SELECT * FROM CNES_LEITO ORDER BY BLOCO, ORDEM, ID", this::leito);
    }

    /** Dá para editar? (banco do painel configurado) */
    public boolean editavel() {
        return banco.configurado();
    }

    public LeitoCnes criar(LeitoCnes.Dados d, String usuario) {
        preparar();
        validar(d, null);
        LocalDateTime agora = LocalDateTime.now();
        int ordem = d.ordem() != null ? d.ordem() : proximaOrdem(d.bloco().trim());
        long id = banco.inserir("INSERT INTO CNES_LEITO (BLOCO, QUARTO, LEITO, PERFIL, ESPECIALIDADE, OBSERVACAO, ORDEM, ATIVO, ATUALIZADO_EM, ATUALIZADO_POR, TIPO) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                d.bloco().trim().toUpperCase(), d.quarto().trim(), d.leito().trim(), d.perfil(), d.especialidade().trim(), vazioNulo(d.observacao()), ordem,
                d.ativo() == null || d.ativo(), Timestamp.valueOf(agora), usuario, tipoDoLeito(d));
        LeitoCnes novo = buscar(id);
        registrar(agora, usuario, "CRIAR", novo, null, texto(novo));
        return novo;
    }

    public LeitoCnes salvar(long id, LeitoCnes.Dados d, String usuario) {
        preparar();
        LeitoCnes antes = buscar(id);
        validar(d, id);
        LocalDateTime agora = LocalDateTime.now();
        banco.jdbc().update("UPDATE CNES_LEITO SET BLOCO=?, QUARTO=?, LEITO=?, PERFIL=?, ESPECIALIDADE=?, OBSERVACAO=?, ORDEM=?, ATIVO=?, ATUALIZADO_EM=?, ATUALIZADO_POR=?, TIPO=? WHERE ID=?",
                d.bloco().trim().toUpperCase(), d.quarto().trim(), d.leito().trim(), d.perfil(), d.especialidade().trim(), vazioNulo(d.observacao()),
                d.ordem() != null ? d.ordem() : antes.ordem(), d.ativo() != null ? d.ativo() : antes.ativo(), Timestamp.valueOf(agora), usuario, tipoDoLeito(d), id);
        LeitoCnes depois = buscar(id);
        String acao = antes.ativo() != depois.ativo() ? (depois.ativo() ? "ATIVAR" : "DESATIVAR") : "ALTERAR";
        registrar(agora, usuario, acao, depois, texto(antes), texto(depois));
        return depois;
    }

    public List<LeitoCnes.Mudanca> historico(int limite) {
        if (!banco.configurado()) return List.of();
        preparar();
        return banco.jdbc().query("SELECT * FROM CNES_HISTORICO ORDER BY QUANDO DESC, ID DESC LIMIT ?", (r, i) -> new LeitoCnes.Mudanca(
                r.getLong("id"), r.getTimestamp("quando").toLocalDateTime(), r.getString("usuario"), r.getString("acao"),
                (Long) r.getObject("leito_id", Long.class), r.getString("bloco"), r.getString("antes"), r.getString("depois")), Math.max(1, Math.min(limite, 2000)));
    }

    private LeitoCnes buscar(long id) {
        List<LeitoCnes> l = banco.jdbc().query("SELECT * FROM CNES_LEITO WHERE ID = ?", this::leito, id);
        if (l.isEmpty()) throw new NaoEncontrado("Leito " + id + " não existe no cadastro CNES.");
        return l.get(0);
    }

    private void validar(LeitoCnes.Dados d, Long id) {
        if (d == null || vazio(d.bloco()) || vazio(d.quarto()) || vazio(d.leito()) || vazio(d.especialidade())) {
            throw new DadoInvalido("Preencha bloco, quarto, leito e especialidade.");
        }
        if (!PERFIS.contains(d.perfil())) throw new DadoInvalido("Perfil deve ser SUS ou CONV/PART.");
        if (d.bloco().trim().length() > 20 || d.quarto().trim().length() > 20 || d.leito().trim().length() > 20 || d.especialidade().trim().length() > 80) {
            throw new DadoInvalido("Texto longo demais (bloco, quarto e leito até 20 letras; especialidade até 80).");
        }
        boolean ativo = d.ativo() == null || d.ativo();
        if (ativo) {
            Integer repetido = banco.jdbc().queryForObject(
                    "SELECT COUNT(*) FROM CNES_LEITO WHERE ATIVO AND UPPER(BLOCO) = UPPER(?) AND QUARTO = ? AND LEITO = ? AND PERFIL = ? AND ESPECIALIDADE = ? AND (? IS NULL OR ID <> ?)",
                    Integer.class, d.bloco().trim(), d.quarto().trim(), d.leito().trim(), d.perfil(), d.especialidade().trim(), id, id);
            if (repetido != null && repetido > 0) throw new DadoInvalido("Já existe um leito ativo igual neste bloco.");
        }
    }

    /** Tipo próprio do leito (validado); vazio = segue o bloco. */
    private String tipoDoLeito(LeitoCnes.Dados d) {
        if (vazio(d.tipo())) return null;
        String t = d.tipo().trim().toUpperCase();
        validarTipo(t);
        return t;
    }

    private int proximaOrdem(String bloco) {
        Integer max = banco.jdbc().queryForObject("SELECT COALESCE(MAX(ORDEM), 0) FROM CNES_LEITO WHERE UPPER(BLOCO) = UPPER(?)", Integer.class, bloco);
        return (max == null ? 0 : max) + 1;
    }

    private void registrar(LocalDateTime quando, String usuario, String acao, LeitoCnes l, String antes, String depois) {
        banco.jdbc().update("INSERT INTO CNES_HISTORICO (QUANDO, USUARIO, ACAO, LEITO_ID, BLOCO, ANTES, DEPOIS) VALUES (?,?,?,?,?,?,?)",
                Timestamp.valueOf(quando), usuario, acao, l.id(), l.bloco(), antes, depois);
    }

    private static String texto(LeitoCnes l) {
        return String.format("%s · %s · %s · %s · %s%s%s%s", l.bloco(), l.quarto(), l.leito(), l.perfil(), l.especialidade(),
                l.observacao() != null ? " · " + l.observacao() : "", l.tipo() != null ? " · tipo " + l.tipo() : "", l.ativo() ? "" : " · inativo");
    }

    private LeitoCnes leito(ResultSet r, int i) throws SQLException {
        return new LeitoCnes(r.getLong("id"), r.getString("bloco"), r.getString("quarto"), r.getString("leito"), r.getString("perfil"),
                r.getString("especialidade"), r.getString("observacao"), r.getInt("ordem"), r.getBoolean("ativo"),
                r.getTimestamp("atualizado_em").toLocalDateTime(), r.getString("atualizado_por"), r.getString("tipo"));
    }

    /** O cadastro que estava no código do painel (lib/utils/cnes.ts), só para leitura e para a primeira carga. */
    List<LeitoCnes> inicial() {
        try (InputStream in = new ClassPathResource("cnes/leitos-inicial.json").getInputStream()) {
            List<Map<String, Object>> linhas = json.readValue(in, new TypeReference<>() { });
            List<LeitoCnes> out = new ArrayList<>();
            long id = 0;
            for (Map<String, Object> m : linhas) {
                out.add(new LeitoCnes(--id, (String) m.get("bloco"), (String) m.get("quarto"), (String) m.get("leito"), (String) m.get("perfil"),
                        (String) m.get("especialidade"), (String) m.get("observacao"), ((Number) m.get("ordem")).intValue(), true, null, null, null));
            }
            return out;
        } catch (IOException e) {
            throw new IllegalStateException("Não foi possível ler o cadastro CNES inicial.", e);
        }
    }

    private static boolean vazio(String s) { return s == null || s.isBlank(); }
    private static String vazioNulo(String s) { return vazio(s) ? null : s.trim(); }

    public static class DadoInvalido extends RuntimeException { public DadoInvalido(String m) { super(m); } }
    public static class NaoEncontrado extends RuntimeException { public NaoEncontrado(String m) { super(m); } }
}
